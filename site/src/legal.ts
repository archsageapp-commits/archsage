// 規約の文書（要求仕様のタブ）に貼るための Markdown
export function legalMarkdown(doc: LegalDoc): string {
  const out = [`## ${doc.title}`, '', ...doc.intro.flatMap((p) => [p, ''])];
  doc.sections.forEach((s, i) => {
    out.push(`### ${i + 1}. ${s.title}`, '');
    if (s.lead) out.push(s.lead, '');
    out.push(...s.items.map((t) => `- ${t}`), '');
  });
  if (doc.closing) out.push(...doc.closing.flatMap((p) => [p, '']));
  return out.join('\n');
}
